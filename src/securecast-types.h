#pragma once

// =============================================================================
// securecast-types.h — 여러 모듈이 공유하는 경량 공통 타입
//
// 순환 include와 무거운 헤더 의존을 피하기 위해, 필터 코어·렌더·UI가 함께 쓰는
// 작은 값 타입만 여기 모아 둔다. 동작 로직은 없고 데이터 정의만 있다.
//   · SecurityState : 경광등/상태 표시용 안전 등급 (초록/노랑/빨강)
//   · BlurRect      : 화면에서 가릴 한 영역(블러 또는 블랙아웃)의 사각형
// =============================================================================

// UI 및 운영 토글 상태
enum class SecurityState {
    SAFE,       // 노출 위험 없음 (초록)
    PARTIAL,    // 위험 감지 후 마스킹 동작 중 (노랑)
    RISK        // 심각한 유출 위험 또는 프레임 오버플로우 (빨강)
};

// 화면 내 개별적인 블러/블랙아웃 처리 영역
struct BlurRect {
    int x;
    int y;
    int width;
    int height;
    int type;       // 0: Blur, 1: Blackout
};
